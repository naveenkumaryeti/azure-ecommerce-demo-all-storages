"""Users are JSON blobs (users/<sha256(email)>.json). Passwords are salted PBKDF2 hashes. Tokens are signed, expiring."""
import hashlib
import logging
import re
import uuid
from functools import wraps

from azure.core.exceptions import ResourceExistsError, ResourceNotFoundError
from flask import g, request
from itsdangerous import BadSignature, URLSafeTimedSerializer
from werkzeug.security import check_password_hash, generate_password_hash

import config
from models.product import now
from services import audit_service as audit
from services import blob_service as bs
from services.errors import AppError, AuthError

log = logging.getLogger(__name__)
U = config.CONTAINERS["users"]
_ser = URLSafeTimedSerializer(config.SESSION_SECRET, salt="quickkart-auth")
EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
PREFIX = {"customer": "CUST", "seller": "SELLER", "admin": "ADMIN"}


def _blob(email):
    return hashlib.sha256(email.strip().lower().encode()).hexdigest()[:32] + ".json"


def create_user(email, name, password, role, uid=None):
    email = (email or "").strip().lower()
    if not EMAIL.match(email):
        raise AppError("a valid email is required")
    if len(password or "") < 8:
        raise AppError("password must be at least 8 characters")
    if not (name or "").strip():
        raise AppError("name is required")
    rec = {"user_id": uid or f"{PREFIX[role]}-{uuid.uuid4().hex[:6].upper()}", "email": email, "name": name.strip(), "role": role,
           "password_hash": generate_password_hash(password, method="pbkdf2:sha256"), "created_at": now()}
    try:
        bs.put_json(U, _blob(email), rec, create_only=True)
    except ResourceExistsError:
        raise AppError("email already registered", 409, "CONFLICT")
    return rec


def public(u):
    return {k: u[k] for k in ("user_id", "email", "name", "role")}


def login(email, password):
    try:
        u, _ = bs.get_json(U, _blob(email or ""))
    except ResourceNotFoundError:
        u = None
    if not u or not check_password_hash(u["password_hash"], password or ""):
        audit.log_event("login_failed", actor_id="anonymous", result="failure")
        raise AuthError("Invalid email or password", 401, "UNAUTHORIZED")
    token = _ser.dumps({"uid": u["user_id"], "role": u["role"], "name": u["name"]})
    audit.log_event(f"{u['role']}_logged_in", u["user_id"], u["user_id"])
    return token, public(u)


def ensure_seed():
    """Seed demo seller/admin/customer from env passwords (generated by deploy.sh). Skips blank passwords."""
    for role, email, pw, uid, name in config.SEEDS:
        if pw:
            try:
                create_user(email, name, pw, role, uid)
            except AppError as e:
                if e.status != 409:
                    raise


def _current():
    h = request.headers.get("Authorization", "")
    if not h.startswith("Bearer "):
        return None
    try:
        return _ser.loads(h[7:], max_age=config.TOKEN_MAX_AGE)
    except BadSignature:
        return None


def require(*roles):
    def deco(fn):
        @wraps(fn)
        def wrapper(*a, **k):
            u = _current()
            if not u:
                raise AuthError("login required", 401, "UNAUTHORIZED")
            if roles and u["role"] not in roles:
                raise AuthError("your role may not perform this action", 403, "FORBIDDEN")
            g.user = u
            return fn(*a, **k)
        return wrapper
    return deco
